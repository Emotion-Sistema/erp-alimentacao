import { test } from "@playwright/test";
import { entrar } from "./ajudas";
test("captura", async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 });
  await entrar(page, "gerente.geral");
  await page.goto("/cadastros/produtos");
  await page.getByRole("button", { name: "Novo produto" }).click();
  const j = page.getByRole("dialog", { name: "Novo produto" });
  await j.getByLabel("Preço (R$)").fill("30,00");
  await j.getByLabel("É um combo?").check();
  await j.getByLabel("Nome da parte 1", { exact: true }).fill("Lanche");
  await j.getByLabel("Produto da opção 1 da parte 1", { exact: true }).selectOption({ label: "Porção de batata frita" });
  await j.getByRole("button", { name: "Adicionar opção em Lanche" }).click();
  await j.getByLabel("Produto da opção 2 da parte 1", { exact: true }).selectOption({ label: "X-Bacon" });
  await j.getByTestId("parte-1").scrollIntoViewIfNeeded();
  await page.screenshot({ path: process.env.SAIDA + "/m1.png" });
  await j.getByTestId("previa-do-preco").scrollIntoViewIfNeeded();
  await page.screenshot({ path: process.env.SAIDA + "/m2.png" });
  await page.setViewportSize({ width: 1280, height: 900 });
  await j.getByTestId("parte-1").scrollIntoViewIfNeeded();
  await page.screenshot({ path: process.env.SAIDA + "/d1.png" });
});
